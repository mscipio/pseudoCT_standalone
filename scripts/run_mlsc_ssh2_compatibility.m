function report = run_mlsc_ssh2_compatibility(varargin)
%RUN_MLSC_SSH2_COMPATIBILITY Run the credential-free MLSC SSH2 audit gate.
%
% This harness is deliberately non-destructive.  With no arguments it
% performs a local compatibility audit of the MLSC SSH2 contract.  The
% optional 'live' selector is accepted for symmetry, but this harness
% never prompts for credentials, opens a network connection, or submits a
% Slurm job in any mode.  Credentials are supplied out-of-band at runtime
% through the existing passwordEntryDialog username/password UX only and
% are never function arguments.
%
% Revised normal-path contract (Launchpad-style, provider-free):
%   * The normal MLSC workflow requires NO host-key provider.  An empty
%     provider selects the existing username/password dialog, the bundled
%     Ganymed password authentication path, runtime account discovery
%     through sshare, and the Slurm lifecycle without known_hosts or
%     fingerprint input or an authentication block.  A missing provider is
%     therefore no longer reported as a normal-workflow trusted-material
%     blocker.
%   * Strict pinned host-key verification remains an optional
%     development/testing capability.  It activates only when an
%     explicitly supplied provider is present and still fails closed on
%     any doubt.
%
% Gate state summary (credential-free audit only -- no network is used):
%   * Crypto/transport compatibility is PROVEN: a successful out-of-band
%     manual diagnostic authenticated to the MLSC login host through the
%     bundled Ganymed library and executed 'hostname; whoami', returning
%     the login hostname.  The authenticated operator identity is
%     deliberately not published in this report, in documentation, or in
%     source control.
%   * The command of record remains 'true'.  Its live numeric exit-status
%     check on the provider-free path is a separate, separately authorized
%     out-of-band readiness step; it is reported NOT_ATTEMPTED here and is
%     never claimed to have completed through this harness.

if nargin > 1 || (nargin == 1 && ...
        (~ischar(varargin{1}) || ~strcmpi(varargin{1}, 'live')))
    error('pseudo_CT:SSH2HarnessArguments', ...
        ['Only the ''live'' selector is accepted. Credentials and host-key ', ...
         'material are never function arguments.']);
end

requested_live = nargin == 1;
target_host = 'mlsc.nmr.mgh.harvard.edu';
target_port = 22;
target_command = 'true';
scripts_dir = fileparts(mfilename('fullpath'));
root_dir = fileparts(scripts_dir);
ssh2_root = fullfile(root_dir, 'ssh2_v2_m1_r5', 'ssh2_v2_m1_r5');
ssh2_main_file = fullfile(ssh2_root, 'ssh2_main.m');
server_verifier_file = fullfile(ssh2_root, 'ganymed-ssh2-m1', ...
    'ganymed-ssh2-m1-source', 'src', 'ch', 'ethz', 'ssh2', ...
    'ServerHostKeyVerifier.java');
known_hosts_file = fullfile(ssh2_root, 'ganymed-ssh2-m1', ...
    'ganymed-ssh2-m1-source', 'src', 'ch', 'ethz', 'ssh2', ...
    'KnownHosts.java');
strict_verifier_file = fullfile(ssh2_root, 'ganymed-ssh2-m1', ...
    'ganymed-ssh2-m1-source', 'src', 'ch', 'ethz', 'ssh2', ...
    'MLSCStrictHostKeyVerifier.java');
host_key_trust_file = fullfile(root_dir, 'src', 'mlsc', ...
    'mlsc_host_key_trust.m');
entrypoint_file = fullfile(root_dir, 'run_pseudo_CT.m');
profile_files = {fullfile(root_dir, 'src', 'config', 'profiles', 'mlsc_legacy.m'), ...
    fullfile(root_dir, 'src', 'config', 'profiles', 'mlsc_mprage_only.m')};

blockers = {};
evidence = {};

% --- Provider-free normal-path seam (Launchpad-style operational model).
ssh2_main_source = local_read_text(ssh2_main_file);
strict_verifier_source = local_read_text(strict_verifier_file);
host_key_trust_source = local_read_text(host_key_trust_file);
entrypoint_source = local_read_text(entrypoint_file);
provider_free_ready = ...
    ~isempty(strfind(entrypoint_source, ...
        'p.addParamValue(''mlsc_host_key_provider'', []')) && ...
    ~isempty(strfind(entrypoint_source, ...
        'strict_host_key_trust = ~isempty(host_key_provider);')) && ...
    ~isempty(strfind(entrypoint_source, ...
        'if strict_host_key_trust && isempty(host_key_verifier)')) && ...
    ~isempty(strfind(entrypoint_source, ...
        '''Login for: %s'', config.mlsc.host')) && ...
    ~isempty(strfind(entrypoint_source, 'sshare -U -u $USER')) && ...
    ~isempty(strfind(entrypoint_source, 'mlsc_parse_slurm_accounts('));
profiles_clean = true;
for ii = 1:length(profile_files)
    if ~isempty(strfind(local_read_text(profile_files{ii}), ...
            'mlsc_host_key_provider'))
        profiles_clean = false;
    end
end
provider_free_ready = provider_free_ready && profiles_clean;
if provider_free_ready
    evidence{end+1} = ['NORMAL_PATH: the normal MLSC workflow is ', ...
        'provider-free. The host-key provider argument defaults to empty; ', ...
        'an empty provider keeps the verifier empty so ssh2_main takes ', ...
        'its existing connect/authenticateWithPassword branch after the ', ...
        'existing username/password dialog, exactly like the Launchpad ', ...
        'operational model, and sshare account discovery plus the Slurm ', ...
        'lifecycle callbacks then proceed normally. A missing provider is ', ...
        'not a trusted-material blocker, and no profile requires the ', ...
        'provider.'];
else
    blockers{end+1} = ['NORMAL_PATH: the provider-free transport/auth/', ...
        'account-flow wiring of the normal MLSC workflow could not be ', ...
        'confirmed from the checked-in sources, so the revised ', ...
        'normal-path contract fails this local audit.'];
end

% --- Strict host-key trust seam: optional development/testing opt-in only.
verifier_seam_ready = ~isempty(ssh2_main_source) && ...
    ~isempty(strfind(ssh2_main_source, ...
        'isfield(ssh2_struct,''server_host_key_verifier''')) && ...
    ~isempty(strfind(ssh2_main_source, ...
        'ssh2_struct.server_host_key_verifier);')) && ...
    ~isempty(strfind(ssh2_main_source, ...
        'ssh2_struct.connection.connect();')) && ...
    ~isempty(strict_verifier_source) && ~isempty(host_key_trust_source) && ...
    ~isempty(strfind(host_key_trust_source, 'MLSCStrictHostKeyVerifier')) && ...
    ~isempty(strfind(entrypoint_source, ...
        'requires a non-null strict host-key verifier'));
if verifier_seam_ready
    evidence{end+1} = ['HOST_KEY_VERIFICATION: strict pinned host-key ', ...
        'trust is an optional development/testing capability, never a ', ...
        'requirement of the normal workflow: mlsc_host_key_trust builds an ', ...
        'in-memory KnownHosts database and a host/port-pinned ', ...
        'MLSCStrictHostKeyVerifier that accepts only HOSTKEY_IS_OK, ', ...
        'ssh2_main passes an explicitly supplied verifier to ', ...
        'Connection.connect(verifier) before authentication, and the MLSC ', ...
        'runtime rejects a null verifier only when a provider was ', ...
        'supplied. Without a provider the empty verifier routes ssh2_main ', ...
        'to its existing connect/authenticateWithPassword branch.'];
else
    blockers{end+1} = ['HOST_KEY_VERIFICATION: the optional strict ', ...
        'pinned host-key seam could not be confirmed from the checked-in ', ...
        'sources, so the development/testing opt-in fails this local ', ...
        'audit; the provider-free normal path itself is unaffected by ', ...
        'this finding.'];
end

% --- Race-safe numeric command exit status seam. ---
exit_status_ready = ~isempty(ssh2_main_source) && ...
    ~isempty(strfind(ssh2_main_source, 'getExitStatus')) && ...
    ~isempty(strfind(ssh2_main_source, 'waitForCondition')) && ...
    ~isempty(strfind(ssh2_main_source, 'command_success = (exit_status == 0)'));
if exit_status_ready
    evidence{end+1} = ['COMMAND_EXIT_STATUS: ssh2_main waits a bounded time ', ...
        'for ChannelCondition.EXIT_STATUS/CLOSED before Session.', ...
        'getExitStatus(); the numeric status is exposed via ', ...
        '.command_exit_status/.command_success and the optional third ', ...
        'ssh2_command output; only 0 maps to success and stdout never ', ...
        'overrides the status. The live numeric check of ', ...
        ['''', target_command, ''' on the provider-free path is a separate ', ...
        'operator-run readiness step, deliberately not performed by this ', ...
        'credential-free audit.']];
else
    blockers{end+1} = ['COMMAND_EXIT_STATUS: race-safe numeric exit-status ', ...
        'support could not be confirmed from ssh2_main, so the local audit ', ...
        'fails closed because ', ['''', target_command, ''''], ...
        ' success could not be proven from the numeric status alone.'];
end

% --- Authentication and crypto compatibility: PROVEN by manual diagnostic.
if ~isempty(ssh2_main_source) && ...
        ~isempty(strfind(ssh2_main_source, 'authenticateWithPassword'))
    evidence{end+1} = ['AUTHENTICATION: a successful out-of-band manual ', ...
        'diagnostic used the bundled Ganymed path to authenticate to ', ...
        target_host, ' and execute ''hostname; whoami''; the output named ', ...
        'the login host ', ['''mlsc-login.nmr.mgh.harvard.edu'''], ...
        ' and the whoami result confirmed the authenticated operator ', ...
        'account. The operator identity is withheld from this report, from ', ...
        'documentation, and from source control. Negotiation, authentication, ', ...
        'and command execution are therefore PROVEN; this diagnostic did ', ...
        'not use a pinned host key, did not run ''', target_command, ''', ', ...
        'and is not a substitute for the live readiness checks.'];
else
    blockers{end+1} = ['AUTHENTICATION: the existing wrapper does not ', ...
        'expose password authentication.'];
end

server_verifier_source = local_read_text(server_verifier_file);
known_hosts_source = local_read_text(known_hosts_file);
if isempty(server_verifier_source) || isempty(known_hosts_source)
    evidence{end+1} = ['CRYPTO_COMPATIBILITY: bundled host-key verification ', ...
        'sources were not available for the credential-free audit; the ', ...
        'manual transport diagnostic result below is unaffected.'];
else
    evidence{end+1} = ['CRYPTO_COMPATIBILITY: PROVEN by the manual transport ', ...
        'diagnostic against ', target_host, ':', num2str(target_port), ...
        ' (negotiation, authentication, and command execution through the ', ...
        'bundled Ganymed library all completed; the returned login hostname ', ...
        'is recorded below). The bundled host-key material path documents ', ...
        'ssh-rsa/ssh-dss handling.'];
end

report = struct();
report.schema = 'pseudo-CT.mlsc-ssh2-compatibility/v2';
report.target_host = target_host;
report.target_port = target_port;
report.command = target_command;
report.transport = 'existing MATLAB ssh2 implementation';
report.credential_source = ['out-of-band at runtime through the existing ', ...
    'passwordEntryDialog username/password UX; not supplied to this harness'];
report.host_key_material = ['optional development/testing material: an ', ...
    'out-of-band pinned known_hosts entry or independently verified ', ...
    'host-key fingerprint supplied only to the strict opt-in path; never ', ...
    'required by the normal MLSC workflow and not supplied to this harness'];
report.normal_path = 'PROVIDER_FREE';
report.live_requested = requested_live;
report.live_validation = 'NOT_ATTEMPTED';
report.host_key_verification = 'OPT_IN';
if exit_status_ready
    report.command_exit_status = 'SEAM_VERIFIED';
else
    report.command_exit_status = 'MISSING';
end
report.authentication = 'PROVEN';
report.crypto_compatibility = 'PROVEN';
report.manual_diagnostic_target = target_host;
report.manual_diagnostic_command = 'hostname; whoami';
report.manual_diagnostic_login_hostname = 'mlsc-login.nmr.mgh.harvard.edu';
report.manual_diagnostic_identity = ['withheld; the exact operator identity ', ...
    'is not published in committed content'];
report.manual_diagnostic_result = 'PROVEN';
report.manual_diagnostic_scope = ['transport negotiation, password ', ...
    'authentication, and command execution only; not a strictly verified ', ...
    'handshake and not a substitute for the live ', ['''', target_command, ''''], ...
    ' readiness check'];
if isempty(blockers)
    report.status = 'PASS_LOCAL_AUDIT';
else
    report.status = 'FAIL_LOCAL_AUDIT';
end
report.blockers = blockers;
report.evidence = evidence;

if ~requested_live
    report.evidence{end+1} = ['CREDENTIAL_FREE: no credentials, host-key ', ...
        'material, network connection, or remote command was used. The ', ...
        'live provider-free readiness steps -- running ', ...
        ['''', target_command, ''''], ' and validating the numeric exit ', ...
        'status, sshare account discovery, and the Slurm lifecycle -- are ', ...
        'separate operator-performed checks and remain NOT_ATTEMPTED in ', ...
        'this audit.'];
else
    report.evidence{end+1} = ['LIVE_NOT_PERFORMED_BY_HARNESS: the live ', ...
        'selector was requested, but this audit harness never prompts for ', ...
        'credentials, connects, or submits by design; run the live ', ...
        'provider-free check out-of-band through the normal MLSC workflow ', ...
        'and validate the numeric exit status there.'];
end

local_print_report(report);
end

function text = local_read_text(file_path)
fid = fopen(file_path, 'r');
if fid == -1
    text = '';
    return;
end
text = fread(fid, inf, '*char')';
fclose(fid);
end

function local_print_report(report)
fprintf('=== MLSC MATLAB SSH2 compatibility audit ===\n');
fprintf('Target: %s:%d\n', report.target_host, report.target_port);
fprintf('Command: %s\n', report.command);
fprintf('Normal MLSC path: %s (a missing provider is not a blocker)\n', ...
    report.normal_path);
fprintf('Live validation: %s\n', report.live_validation);
fprintf('Host-key verification: %s (strict trust is an optional development/testing opt-in)\n', ...
    report.host_key_verification);
fprintf('Command exit status: %s\n', report.command_exit_status);
fprintf('Authentication: %s\n', report.authentication);
fprintf('Crypto compatibility: %s\n', report.crypto_compatibility);
fprintf('Manual transport diagnostic: %s (%s -> login host %s)\n', ...
    report.manual_diagnostic_result, report.manual_diagnostic_command, ...
    report.manual_diagnostic_login_hostname);
fprintf('Manual diagnostic identity: %s\n', report.manual_diagnostic_identity);
if isempty(report.blockers)
    fprintf('Blockers: none reported by the credential-free audit.\n');
else
    fprintf('Blockers:\n');
    for ii = 1:length(report.blockers)
        fprintf('  - %s\n', report.blockers{ii});
    end
end
fprintf('Result: %s\n', report.status);
end
