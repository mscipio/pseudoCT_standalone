function observed = pseudo_CT_completion_failure_observed(lifecycle)
%PSEUDO_CT_COMPLETION_FAILURE_OBSERVED Require terminal output/finalization evidence.
%   A terminal scheduler record or its exit code alone does not establish a
%   scientific completion outcome. FAILED requires an observed output
%   verification failure or an attempted local finalization failure.
%   Minimum supported MATLAB: R2010b.

observed = false;
try
    if ~isstruct(lifecycle) || numel(lifecycle) ~= 1 || ...
            ~isfield(lifecycle, 'terminal') || ...
            ~isequal(lifecycle.terminal, true) || ...
            ~isfield(lifecycle, 'accounting_record_found') || ...
            ~isequal(lifecycle.accounting_record_found, true)
        return;
    end

    output_failure = false;
    if isfield(lifecycle, 'workflow_state') && ...
            ischar(lifecycle.workflow_state) && ...
            strcmp(lifecycle.workflow_state, 'failed') && ...
            isfield(lifecycle, 'copy_back') && ...
            isstruct(lifecycle.copy_back) && ...
            isfield(lifecycle.copy_back, 'contract_represented') && ...
            isequal(lifecycle.copy_back.contract_represented, true) && ...
            isfield(lifecycle.copy_back, 'verified') && ...
            isequal(lifecycle.copy_back.verified, false) && ...
            isfield(lifecycle, 'failure') && ...
            isstruct(lifecycle.failure) && ...
            isfield(lifecycle.failure, 'present') && ...
            isequal(lifecycle.failure.present, true) && ...
            isfield(lifecycle.failure, 'detail') && ...
            ischar(lifecycle.failure.detail) && ...
            ~isempty(strtrim(lifecycle.failure.detail))
        output_failure = true;
    end

    finalization_failure = false;
    if isfield(lifecycle, 'finalization') && ...
            isstruct(lifecycle.finalization) && ...
            isfield(lifecycle.finalization, 'attempted') && ...
            isequal(lifecycle.finalization.attempted, true) && ...
            isfield(lifecycle.finalization, 'succeeded') && ...
            isequal(lifecycle.finalization.succeeded, false) && ...
            isfield(lifecycle.finalization, 'status') && ...
            ischar(lifecycle.finalization.status) && ...
            strcmp(lifecycle.finalization.status, 'failed')
        finalization_failure = true;
    end
    observed = output_failure || finalization_failure;
catch %#ok<CTCH>
    observed = false;
end
end
