function result = pseudo_CT_validate_headless_result(result_path, ...
        expected_invocation_id, expected_profile)
%PSEUDO_CT_VALIDATE_HEADLESS_RESULT Validate one bound v2 result MAT file.
%   The result must have the exact schema, invocation/profile binding, and
%   coherent validation or submit statuses. Minimum supported MATLAB: R2010b.

if nargin ~= 3 || ~local_plain_text(result_path) || ...
        ~local_uuid(expected_invocation_id) || ~local_allowed_profile(expected_profile)
    error('pseudo_CT:HeadlessResult', ...
        'A result path and valid expected invocation/profile are required.');
end
if exist(result_path, 'file') ~= 2 || ~local_mat_v5(result_path)
    error('pseudo_CT:HeadlessResult', ...
        'Result MAT file is unavailable or is not MATLAB v5 format.');
end
variables = whos('-file', result_path);
if length(variables) ~= 1 || ~strcmp(variables(1).name, 'result') || ...
        ~strcmp(variables(1).class, 'struct') || ...
        ~isequal(variables(1).size, [1 1])
    error('pseudo_CT:HeadlessResult', 'Result MAT schema is invalid.');
end
loaded = load(result_path, 'result');
if ~isfield(loaded, 'result')
    error('pseudo_CT:HeadlessResult', 'Result MAT schema is invalid.');
end
result = loaded.result;
clear loaded
required = {'schema'; 'invocation_id'; 'action'; 'profile'; 'status'; ...
    'error_code'; 'error_message'; 'authentication_status'; ...
    'submission_status'; 'backend'; 'group_account'; 'job_ids'; ...
    'scientific_completion'; 'dispatch_status'; 'resolved_job'; ...
    'evidence'; 'diagnostics'};
if ~isstruct(result) || numel(result) ~= 1 || ...
        ~isequal(sort(fieldnames(result)), sort(required)) || ...
        ~strcmp(result.schema, 'pseudoCT.headless-result/v2') || ...
        ~local_uuid(result.invocation_id) || ...
        ~local_enum(result.action, {'validate'; 'submit'; 'authenticate'}) || ...
        ~local_allowed_profile(result.profile) || ...
        ~local_enum(result.status, {'ready'; 'submitted'; 'failed'}) || ...
        ~local_enum(result.error_code, {'', 'INVALID_REQUEST', ...
        'PROFILE_NOT_ALLOWED', 'AUTHENTICATION_FAILED', 'INVALID_GROUP_ACCOUNT', ...
        'NO_ACCOUNTS', 'ACCOUNT_QUERY_FAILED', 'STALE_RESOLVED_JOB', 'HOST_KEY_UNAVAILABLE', ...
        'CREDENTIAL_ERASE_FAILED', 'CREDENTIAL_STORAGE_FAILED', 'SUBMIT_FAILED', ...
        'VALIDATION_FAILED', 'AUTHENTICATION_STEP_FAILED'}) || ...
        ~local_plain_text(result.error_message) || ...
        ~local_enum(result.authentication_status, {'not_attempted'; ...
        'authenticated'; 'failed'; 'not_observed'; 'not_applicable'}) || ...
        ~local_enum(result.submission_status, {'not_attempted'; 'accepted'; ...
        'rejected'; 'unresolved'; 'not_observed'}) || ...
        ~local_enum(result.backend, {'local'; 'mlsc'}) || ...
        ~local_plain_text(result.group_account) || ...
        ~local_job_ids(result.job_ids) || ...
         ~local_enum(result.scientific_completion, {'not_applicable'; ...
         'not_observed'; 'completed'; 'failed'}) || ...
         ~local_enum(result.dispatch_status, {'not_dispatched'; 'dispatched'; 'failed'}) || ...
         ~strcmp(result.backend, local_backend(result.profile)) || ...
          ~isstruct(result.evidence) || numel(result.evidence) ~= 1 || ...
          ~isstruct(result.diagnostics) || ...
          ~local_diagnostics(result.diagnostics)
    error('pseudo_CT:HeadlessResult', ...
        'Result schema, status, or field types are invalid.');
end
if ~strcmp(result.invocation_id, expected_invocation_id) || ...
        ~strcmp(result.profile, expected_profile)
    error('pseudo_CT:HeadlessResultBinding', ...
        'Result belongs to another invocation or profile.');
end
if ~isempty(result.error_code) ~= ~isempty(result.error_message) || ...
        ~strcmp(result.diagnostics.code, result.error_code) || ...
        ~strcmp(result.diagnostics.message, result.error_message)
    error('pseudo_CT:HeadlessResult', 'Result failure diagnostics are inconsistent.');
end
if strcmp(result.action, 'validate')
    % A remote validate may carry an authenticated account check (no submission);
    % local validate never authenticates.
    if strcmp(result.backend, 'local')
        account_ok = strcmp(result.authentication_status, 'not_attempted');
    else
        account_ok = any(strcmp(result.authentication_status, ...
            {'not_attempted'; 'authenticated'; 'failed'}));
    end
    if ~any(strcmp(result.status, {'ready'; 'failed'})) || ~account_ok || ...
            ~strcmp(result.submission_status, 'not_attempted') || ...
            ~strcmp(result.dispatch_status, 'not_dispatched') || ...
            ~isempty(result.job_ids) || ...
             ~strcmp(result.scientific_completion, 'not_applicable') || ...
             (~local_resolved_job(result.resolved_job) && ...
             ~(strcmp(result.status, 'failed') && ...
             local_empty_resolved_job(result.resolved_job))) || ...
             (local_resolved_job(result.resolved_job) && ...
             (~strcmp(result.resolved_job.profile, result.profile) || ...
             ~strcmp(result.resolved_job.invocation_id, result.invocation_id))) || ...
             strcmp(result.error_code, 'SUBMIT_FAILED') || ...
              (strcmp(result.status, 'ready') ~= isempty(result.error_code))
        error('pseudo_CT:HeadlessResult', 'Validate result statuses are inconsistent.');
    end
elseif strcmp(result.action, 'authenticate')
    % Authenticate: no submission, no job and no resolved job. Ready means the
    % account was selected after authentication; failed carries an error code.
    if ~any(strcmp(result.status, {'ready'; 'failed'})) || ...
            (strcmp(result.status, 'ready') ~= isempty(result.error_code)) || ...
            (strcmp(result.status, 'ready') && ...
            (~strcmp(result.authentication_status, 'authenticated') || ...
            ~strcmp(result.backend, 'mlsc'))) || ...
            ~strcmp(result.submission_status, 'not_attempted') || ...
            ~strcmp(result.dispatch_status, 'not_dispatched') || ...
            ~isempty(result.job_ids) || ...
            ~strcmp(result.scientific_completion, 'not_applicable') || ...
            ~local_empty_resolved_job(result.resolved_job)
        error('pseudo_CT:HeadlessResult', 'Authenticate result statuses are inconsistent.');
    end
elseif (~local_resolved_job(result.resolved_job) && ...
        ~(strcmp(result.status, 'failed') && ...
        local_empty_resolved_job(result.resolved_job))) || ...
        (local_resolved_job(result.resolved_job) && ...
        (isempty(result.resolved_job.subjects) || ...
        ~strcmp(result.resolved_job.profile, result.profile) || ...
        ~strcmp(result.resolved_job.invocation_id, result.invocation_id))) || ...
        strcmp(result.error_code, 'VALIDATION_FAILED') || ...
        ~any(strcmp(result.status, {'submitted'; 'failed'})) || ...
         (strcmp(result.submission_status, 'accepted') && ...
         (~strcmp(result.authentication_status, 'authenticated') || ...
         isempty(result.job_ids) || ~strcmp(result.dispatch_status, 'dispatched'))) || ...
          (~strcmp(result.backend, 'local') && ...
          any(strcmp(result.scientific_completion, {'completed'; 'failed'})) && ...
         (~strcmp(result.submission_status, 'accepted') || ...
         isempty(result.job_ids) || ~strcmp(result.dispatch_status, 'dispatched'))) || ...
         (strcmp(result.backend, 'local') && ...
         ~local_submit_status(result)) || ...
         (~strcmp(result.backend, 'local') && ...
         ((strcmp(result.status, 'submitted') && ~isempty(result.error_code)) || ...
         (strcmp(result.status, 'failed') && isempty(result.error_code))))
    error('pseudo_CT:HeadlessResult', 'Submit result statuses are inconsistent.');
end

end
function valid = local_empty_resolved_job(value)
valid = isstruct(value) && numel(value) == 1 && isempty(fieldnames(value));
end

function valid = local_resolved_job(job)
valid = isstruct(job) && numel(job) == 1;
if ~valid
    return;
end
required = {'schema'; 'profile'; 'invocation_id'; 'subjects'; 'options'; ...
    'output_config'; 'artifact_identity'; 'current_artifact_root'; ...
    'validation_evidence'};
valid = isequal(sort(fieldnames(job)), sort(required)) && ...
    local_plain_text(job.schema) && strcmp(job.schema, 'pseudoCT.resolved-job/v1') && ...
    local_allowed_profile(job.profile) && local_uuid(job.invocation_id) && ...
    isstruct(job.subjects) && isstruct(job.options) && numel(job.options) == 1 && ...
    isstruct(job.output_config) && numel(job.output_config) == 1 && ...
    isstruct(job.artifact_identity) && numel(job.artifact_identity) == 1 && ...
    isstruct(job.validation_evidence) && numel(job.validation_evidence) == 1 && ...
    local_plain_text(job.current_artifact_root) && ...
     local_resolved_options(job.options) && ...
    local_flag_scalar(job.options.correct_aliasing) && ...
    local_flag_scalar(job.options.recenter_before_normalization) && ...
    isequal(sort(fieldnames(job.output_config)), {'layout'}) && ...
    local_plain_text(job.output_config.layout) && ...
    strcmp(job.output_config.layout, 'profile-default') && ...
    local_safe_serializable(job);
if ~valid
    return;
end
for ii = 1:length(job.subjects)
    fields = {'mprage_fn'; 'umap_fn'; 'correct_aliasing'; ...
        'recenter_before_normalization'; 'io_policy'; 'processing_dir'; ...
        'temp_dir'; 'save_dir'; 'mprage_identity'; 'umap_identity'; ...
        'umap_resolution'};
    valid = isequal(sort(fieldnames(job.subjects(ii))), sort(fields));
    if ~valid
        return;
    end
    subject = job.subjects(ii);
    if ~local_plain_text(subject.mprage_fn) || isempty(subject.mprage_fn) || ...
            ~local_plain_text(subject.umap_fn) || ...
            ~local_plain_text(subject.processing_dir) || ...
            ~local_plain_text(subject.temp_dir) || ...
            ~local_plain_text(subject.save_dir) || ...
             ~local_flag_scalar(subject.correct_aliasing) || ...
             ~local_flag_scalar(subject.recenter_before_normalization) || ...
            ~isstruct(subject.io_policy) || numel(subject.io_policy) ~= 1 || ...
            ~isstruct(subject.mprage_identity) || ...
            numel(subject.mprage_identity) ~= 1 || ...
            ~isstruct(subject.umap_identity) || numel(subject.umap_identity) ~= 1 || ...
            ~local_plain_text(subject.umap_resolution)
        valid = false;
        return;
    end
    forbidden = {'username'; 'password'; 'credentials'; 'transport'; ...
        'session'; 'token'; 'secret'};
    names = fieldnames(job.subjects(ii));
    for jj = 1:length(names)
        if any(strcmpi(names{jj}, forbidden))
            valid = false;
            return;
        end
    end
end
end

function valid = local_resolved_options(options)
names = sort(fieldnames(options));
required = sort({'correct_aliasing'; 'recenter_before_normalization'});
valid = isequal(names, required) || isequal(names, ...
    sort({'correct_aliasing'; 'recenter_before_normalization'; ...
    'cleanup_on_success'}));
if ~valid
    return;
end
valid = local_flag_scalar(options.correct_aliasing) && ...
    local_flag_scalar(options.recenter_before_normalization);
if valid && isfield(options, 'cleanup_on_success')
    valid = local_flag_scalar(options.cleanup_on_success);
end
end

function valid = local_flag_scalar(value)
% R2010b-compatible v5 MAT readers may expose serialized logical flags as
% uint8. Accept only the exact scalar 0/1 representation in either type.
valid = (islogical(value) && isscalar(value)) || ...
    (isa(value, 'uint8') && isscalar(value) && ...
    any(value == uint8([0 1])));
end

function valid = local_submit_status(result)
% Local jobs execute directly: they have no authentication, scheduler
% submission acknowledgement, group account, or scheduler job ID.
no_scheduler = strcmp(result.authentication_status, 'not_attempted') && ...
    strcmp(result.submission_status, 'not_attempted') && ...
    isempty(result.group_account) && isempty(result.job_ids);
if strcmp(result.status, 'submitted')
    valid = no_scheduler && strcmp(result.dispatch_status, 'dispatched') && ...
        isempty(result.error_code) && ...
        strcmp(result.scientific_completion, 'completed');
else
    valid = no_scheduler && ~isempty(result.error_code) && ...
        (any(strcmp(result.dispatch_status, {'not_dispatched'; 'failed'})) || ...
        (strcmp(result.dispatch_status, 'dispatched') && ...
        any(strcmp(result.scientific_completion, {'not_observed'; 'failed'}))));
end
end

function valid = local_safe_serializable(value)
valid = true;
if isstruct(value)
    forbidden = {'username'; 'password'; 'credentials'; 'credential'; ...
        'transport'; 'session'; 'token'; 'secret'};
    names = fieldnames(value);
    for ii = 1:length(names)
        name = lower(names{ii});
        if any(strcmp(name, forbidden)) || ...
                ~isempty(strfind(name, 'credential')) || ...
                ~local_safe_serializable({value.(names{ii})})
            valid = false;
            return;
        end
    end
elseif iscell(value)
    for ii = 1:numel(value)
        if ~local_safe_serializable(value{ii})
            valid = false;
            return;
        end
    end
elseif ~(ischar(value) || isnumeric(value) || islogical(value))
    valid = false;
end
end

function valid = local_diagnostics(value)
valid = isstruct(value) && numel(value) == 1 && ...
    isequal(sort(fieldnames(value)), sort({'code'; 'message'})) && ...
    local_plain_text(value.code) && local_plain_text(value.message);
end

function valid = local_job_ids(value)
valid = isnumeric(value) && isreal(value) && (isempty(value) || isvector(value));
if valid && ~isempty(value)
    valid = ~any(isnan(value(:))) && ~any(isinf(value(:))) && ...
        all(value(:) > 0) && all(value(:) == fix(value(:)));
end
end

function backend = local_backend(profile)
if any(strcmp(profile, {'mlsc'; 'mlsc-mprage-only'}))
    backend = 'mlsc';
else
    backend = 'local';
end
end

function valid = local_plain_text(value)
valid = ischar(value) && (isempty(value) || size(value, 1) == 1) && ...
    ~any(value == char(0));
end

function valid = local_uuid(value)
valid = local_plain_text(value) && ~isempty(regexp(value, ...
    '^[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}$', ...
    'once'));
end

function valid = local_allowed_profile(value)
valid = local_plain_text(value) && any(strcmp(value, ...
    {'mlsc'; 'mlsc-mprage-only'; ...
    'local'; 'local-mprage-only'}));
end

function valid = local_enum(value, choices)
valid = local_plain_text(value) && any(strcmp(value, choices));
end

function valid = local_mat_v5(path_name)
valid = false;
fid = fopen(path_name, 'rb');
if fid == -1
    return;
end
header = fread(fid, 19, 'uint8');
fclose(fid);
valid = length(header) == 19 && strcmp(char(header(:)'), 'MATLAB 5.0 MAT-file');
end
