function profiles = pseudo_CT_profile_choices()
%PSEUDO_CT_PROFILE_CHOICES Static profile table for the MATLAB frontend.
%   Presentation text and GUI defaults copied from src/config/profiles (the
%   profile files remain the authority; the launcher validates the real
%   profile). Installed distributions carry no src/ tree, so the frontend
%   reads this table instead of scanning profile files. A source-mode test
%   (test_frontend_launch) compares every field with pseudo_CT_load_profile.
%   Each element has name, display_name, description, group, recommended,
%   order and config (mode, io_policy, GUI defaults, presentation).
%   Minimum supported MATLAB: R2010b.

rows = {
    'local', 'Local MATLAB - This Computer', ...
    'Run the pseudoCT workflow locally using the shared compiled science payload.', ...
    'recommended', false, 10, 'local', 'umap-required', 'nifti-and-dicom', 'mMR';
    'local-mprage-only', 'Local MPRAGE Only', ...
    'Generate a NIfTI-only pseudoCT locally from MPRAGE alone using the shared current-science payload. No UMAP required.', ...
    'specialized', false, 10, 'local', 'none', 'nifti-only', 'mprage-only';
    'mlsc', 'MLSC', ...
    'Run the pseudoCT pipeline on MLSC using the compiled MATLAB R2010b backend.', ...
    'specialized', true, 15, 'mlsc', 'umap-required', 'nifti-and-dicom', 'mMR';
    'mlsc-mprage-only', 'MPRAGE-only — MLSC', ...
    'Generate a NIfTI-only pseudoCT from MPRAGE alone on MLSC. No UMAP required.', ...
    'specialized', false, 20, 'mlsc', 'none', 'nifti-only', 'mprage-only'};

profiles = struct('name', {}, 'display_name', {}, 'description', {}, ...
    'group', {}, 'recommended', {}, 'order', {}, 'config', {});
for kk = 1:size(rows, 1)
    row = rows(kk, :);
    presentation = struct('display_name', row{2}, 'description', row{3}, ...
        'group', row{4}, 'recommended', row{5}, 'order', row{6});
    config = struct('profile_key', row{1}, 'mode', row{7}, ...
        'io_policy', struct('reference', row{8}, 'output', row{9}, 'gui', row{10}), ...
        'aliasing_default', 1, 'recenter_before_normalization', 'Yes', ...
        'cleanup_on_success', true, 'presentation', presentation);
    profiles(kk) = struct('name', row{1}, 'display_name', row{2}, ...
        'description', row{3}, 'group', row{4}, 'recommended', row{5}, ...
        'order', row{6}, 'config', config);
end
end
